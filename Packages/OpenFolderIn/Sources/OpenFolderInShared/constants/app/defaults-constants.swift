/// Fixed facts about what the app arrives with.
public enum DefaultsConstants {

    /// The name of the shipped list of apps, without its extension.
    public static let builtInAppsResource = "built-in-apps"

    /// The extension of the shipped data files.
    public static let builtInAppsExtension = "json"

    /// The bundle name of the app every mac has, used when nothing else is installed.
    public static let fallbackBundleIdentifier = "com.apple.finder"
}
